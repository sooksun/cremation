import type { FundFacts } from './fund-facts.service';

const baht = (n: number) => n.toLocaleString('th-TH', { maximumFractionDigits: 2 });

function factsBlock(facts: FundFacts): string[] {
  return [
    '===== ข้อมูลระบบ ณ ขณะนี้ =====',
    `จำนวนสมาชิกที่ร่วมจ่ายเงินสงเคราะห์ ณ ขณะนี้: ${baht(facts.payingMemberCount)} คน`,
    facts.isFixedAmount
      ? 'หมายเหตุ: คณะกรรมการกำหนดยอดเงินสงเคราะห์ต่อศพแบบตายตัวไว้ ระบบจึงไม่ได้คูณตามจำนวนสมาชิก'
      : 'ยอดด้านล่างคำนวณจากจำนวนสมาชิกข้างต้น × อัตราเก็บต่อคน',
    `กรณีสมาชิกเสียชีวิต: เก็บคนละ ${baht(facts.memberDeath.rate)} บาท → รวม ${baht(facts.memberDeath.gross)} บาท → หักเข้ากองทุน 10% = ${baht(facts.memberDeath.fundReserve)} บาท → จ่ายผู้มีสิทธิ 90% = ${baht(facts.memberDeath.netToPay)} บาท`,
    `กรณีญาติสายตรงเสียชีวิต: เก็บคนละ ${baht(facts.protectedDeath.rate)} บาท → รวม ${baht(facts.protectedDeath.gross)} บาท → หักเข้ากองทุน 10% = ${baht(facts.protectedDeath.fundReserve)} บาท → จ่ายผู้มีสิทธิ 90% = ${baht(facts.protectedDeath.netToPay)} บาท`,
    'ตัวเลขชุดนี้เป็นยอดรวมทั้งกองทุน ไม่ใช่ข้อมูลของสมาชิกรายใดรายหนึ่ง และเปลี่ยนได้ตลอดเวลาตามจำนวนสมาชิก',
    '===== จบข้อมูลระบบ =====',
  ];
}

