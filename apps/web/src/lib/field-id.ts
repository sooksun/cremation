/**
 * สร้าง id ของช่องกรอกจากชื่อฟิลด์ของ react-hook-form
 *
 * ชื่อฟิลด์ไม่ซ้ำกันอยู่แล้วในหนึ่งฟอร์ม รวมถึงในแถวที่วนซ้ำ เช่น
 * `beneficiaries.0.road` กับ `beneficiaries.1.road` จึงใช้เป็นฐานของ id ได้ปลอดภัย
 *
 * เขียน id ตายตัวไม่ได้ เพราะบล็อกที่อยู่ในลูปหรือในคอมโพเนนต์ที่ถูกใช้ซ้ำ
 * จะได้ id เดียวกันทุกแถว แล้ว <label htmlFor> จะไปผูกกับช่องแรกช่องเดียว
 * ผู้ใช้โปรแกรมอ่านหน้าจอจะได้ยินชื่อผิดแถว และการคลิกป้ายจะโฟกัสผิดช่อง
 */
export function fieldId(name: string): string {
  return `f-${name.replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-|-$/g, '')}`;
}
