import { shapeThai } from './membership-register-pdf';

/**
 * ตารางนี้ได้จากการวัดจริง ไม่ได้อ้างตำรา — เรนเดอร์คำทดสอบด้วย THSarabunNew
 * บนเบราว์เซอร์ซึ่ง shape ถูกต้องผ่าน HarfBuzz แล้วเทียบระดับพิกเซลกับ glyph
 * ในโซน PUA ทุกตัว เลือกตัวที่ตรงกัน 100%
 *
 * fontkit ที่ pdf-lib ใช้ไม่ทำ shaping ภาษาไทยให้ (ฟอนต์ไม่มีฟีเจอร์ mark/mkmk)
 * ถ้าส่งยูนิโคดดิบเข้าไป วรรณยุกต์จะลอยสูงเหนือพยัญชนะทั่วไป
 */
const U = (n: number) => String.fromCodePoint(n);

describe('shapeThai', () => {
  describe('วรรณยุกต์เหนือพยัญชนะทั่วไปที่ไม่มีสระบน — ต้องลดระดับลงมา', () => {
    it.each([
      ['แม่', 'แม' + U(0xf70a)],
      ['บ้าน', 'บ' + U(0xf70b) + 'าน'],
      ['ผ่าน', 'ผ' + U(0xf70a) + 'าน'],
      ['ก๊าซ', 'ก' + U(0xf70c) + 'าซ'],
      ['ปุ๋ย', 'ปุ๋ย'],
      ['หมู่', 'หมู' + U(0xf70a)],
      ['เก๋ง', 'เก' + U(0xf70d) + 'ง'],
    ])('%s', (input, expected) => {
      expect(shapeThai(input)).toBe(expected);
    });
  });

  describe('วรรณยุกต์เหนือพยัญชนะหางสูง (ป ฝ ฟ) ที่ไม่มีสระบน — ใช้ glyph ปกติ', () => {
    it.each([
      ['ป่า', 'ป่า'],
      ['ฟ้า', 'ฟ้า'],
      ['ฝ้าย', 'ฝ้าย'],
      ['ปู่', 'ปู่'],
    ])('%s', (input, expected) => {
      expect(shapeThai(input)).toBe(expected);
    });
  });

  describe('วรรณยุกต์ซ้อนเหนือสระบน', () => {
    it('พยัญชนะทั่วไปใช้ glyph ปกติ', () => {
      expect(shapeThai('ที่')).toBe('ที่');
      expect(shapeThai('ชั่ว')).toBe('ชั่ว');
      expect(shapeThai('สิ้น')).toBe('สิ้น');
    });

    it('พยัญชนะหางสูงต้องเลื่อนซ้ายหลบหาง', () => {
      expect(shapeThai('ปั่น')).toBe('ป' + U(0xf710) + U(0xf713) + 'น');
      expect(shapeThai('ปี้')).toBe('ป' + U(0xf702) + U(0xf714));
      expect(shapeThai('ปั๊ม')).toBe('ป' + U(0xf710) + U(0xf715) + 'ม');
      expect(shapeThai('ฝั่ง')).toBe('ฝ' + U(0xf710) + U(0xf713) + 'ง');
    });
  });

  describe('สระบนเหนือพยัญชนะหางสูง — ต้องเลื่อนซ้าย', () => {
    it.each([
      ['ปิด', 'ป' + U(0xf701) + 'ด'],
      ['ปี', 'ป' + U(0xf702)],
      ['ฝึก', 'ฝ' + U(0xf703) + 'ก'],
      ['ฟื้น', 'ฟ' + U(0xf704) + U(0xf714) + 'น'],
      ['ผัก', 'ผัก'],
    ])('%s', (input, expected) => {
      expect(shapeThai(input)).toBe(expected);
    });
  });

  // ผ สูง 1253 และ ฬ สูง 1350 เท่าพยัญชนะทั่วไป (ก ม น = 1253, ส = 1337)
  // ต่างจาก ป ฝ ฟ ที่สูง 1751 — เคยถูกจัดเป็นหางสูงผิด ทำให้สระเลื่อนซ้ายไปทับตัวอักษร
  describe('ผ และ ฬ ไม่ใช่พยัญชนะหางสูง', () => {
    it.each([
      ['ผี', 'ผ' + 'ี'],
      ['ผู้', 'ผู' + U(0xf70b)],
      ['ผู้ใหญ่', 'ผู' + U(0xf70b) + 'ใหญ' + U(0xf70a)],
      ['ฬ่า', 'ฬ' + U(0xf70a) + 'า'],
    ])('%s', (input, expected) => {
      expect(shapeThai(input)).toBe(expected);
    });
  });

  describe('สระล่างใต้ ฎ ฏ — ต้องลดระดับหลบหาง', () => {
    it.each([
      ['ปฏิบัติ', 'ปฏิบัติ'],
      ['กฎุ', 'กฎ' + U(0xf718)],
      ['ฏู', 'ฏ' + U(0xf719)],
    ])('%s', (input, expected) => {
      expect(shapeThai(input)).toBe(expected);
    });
  });

  // HarfBuzz ไม่ตัดเชิง ฐ ญ ในฟอนต์นี้ การตัดเชิงจะทำให้ PDF ต่างจากที่เห็นบนเว็บ
  describe('ฐ และ ญ ไม่ตัดเชิง', () => {
    it.each([['ฐานะ', 'ฐานะ'], ['ญาติ', 'ญาติ'], ['ฐุ', 'ฐุ'], ['ญุ', 'ญุ']])(
      '%s',
      (input, expected) => {
        expect(shapeThai(input)).toBe(expected);
      },
    );
  });

  describe('การันต์หลังสระบนบนพยัญชนะทั่วไป — ใช้ glyph ปกติ', () => {
    it.each([['สิทธิ์', 'สิทธิ์'], ['ศิลป์', 'ศิลป์']])('%s', (input, expected) => {
      expect(shapeThai(input)).toBe(expected);
    });
  });

  describe('ข้อความที่ไม่มีเครื่องหมายต้องไม่ถูกแตะ', () => {
    it.each([['เชียงราย'], ['กรุงเทพมหานคร'], [''], ['0812345678']])('%s', (input) => {
      expect(shapeThai(input)).toBe(input);
    });
  });
});

// สระอำเขียนไว้หลังวรรณยุกต์ แต่นิคหิตของมันอยู่ด้านบน วรรณยุกต์จึงต้องอยู่สูงเหนือนิคหิต
describe('วรรณยุกต์ที่ตามด้วยสระอำ', () => {
  it.each([['น้ำ', 'น้ำ'], ['ค่ำ', 'ค่ำ'], ['ซ้ำ', 'ซ้ำ']])('%s', (input, expected) => {
    expect(shapeThai(input)).toBe(expected);
  });
});
